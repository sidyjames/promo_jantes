      <h1 style="text-align: center;">Qu'est-ce que le déport et l'ET ?</h1><br>
      <p style="text-align: justify;">
        Le déport que l'on appelle aussi offset ou encore ET correspond à la distance séparant l'axe d'une jante (le milieu de la jante) au moyeu de roue (la surface d'appui). 
        Plus on augmente le déport et plus la jante rentre vers l'intérieur de la roue. 
        Il convient donc de ne pas choisir un déport trop élevé ou au contraire trop bas, auquel cas la jante toucherait la carroserie. La jante sort vers l'extérieur.
